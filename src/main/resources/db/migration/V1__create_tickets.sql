-- Initial schema for the ticket-triage service.
-- Portable DDL: valid on both PostgreSQL and H2 (PostgreSQL-compatibility mode).
CREATE TABLE tickets (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject         VARCHAR(200)  NOT NULL,
    body            VARCHAR(10000) NOT NULL,
    severity        VARCHAR(16),
    suggested_queue VARCHAR(100),
    rationale       VARCHAR(1000),
    triage_status   VARCHAR(16)   NOT NULL,
    created_at      TIMESTAMP     NOT NULL
);

-- Listing is filtered by severity and ordered by recency.
CREATE INDEX idx_tickets_severity   ON tickets (severity);
CREATE INDEX idx_tickets_created_at ON tickets (created_at);
CREATE INDEX idx_tickets_status     ON tickets (triage_status);
